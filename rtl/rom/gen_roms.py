"""ROM generator. CLAUDE.md section 7: ROMs are generated at build time from config/,
never hand-typed.

M2 scope: only the per-level free-evolution rotator ROM (cos/sin of
w01*(n+1/2)*dt, CLAUDE.md section 2) is generated here -- that's what
rtl/src/free_evolution_engine.v consumes. sqrt(n) (drive ladder) and n*(n-1)/2 (Kerr)
ROMs belong to the drive/Duffing datapath, which has not been built yet.

Run: venv/bin/python rtl/rom/gen_roms.py
"""
from __future__ import annotations

from pathlib import Path
from typing import Any

import numpy as np

from physics.fixed_point import Q_FORMATS, quantize
from physics.hamiltonians import load_config
from rtl.rom.hexio import write_hex_file

RTL_ROM_DIR = Path(__file__).resolve().parent


# Fixed ROM width, decoupled from the state's committed Q-format. The rotator ROM
# stores cos/sin(theta_n) -- always in [-1, 1], so 1 int bit suffices regardless of the
# state format's int_bits -- and there are only N_LEVELS entries, so a wider ROM costs a
# small, fixed amount of extra BRAM rather than scaling with anything. This is the fix
# for the V5 regression documented in docs/validation.md: the dominant error source was
# the ROM's quantized rotation *angle* (a small, fixed per-step frequency error that
# compounds ~linearly over the step count), not per-step state rounding -- verified in
# physics/fixed_point.py-style Python sweeps before this was implemented in RTL. Sharing
# a single 16-bit width between the state (which must persist between steps, so its
# quantization is coupled to accumulated drift) and the ROM (a build-time constant that
# costs nothing extra per level) was conflating two different roles.
ROM_INT_BITS = 1
ROM_DATA_WIDTH = 32
ROM_FRAC_BITS = ROM_DATA_WIDTH - ROM_INT_BITS


def generate_free_evolution_roms(cfg: dict[str, Any] | None = None) -> dict[str, int]:
    """Returns the widths/params needed by free_evolution_engine.v (also written to
    rom_params.vh)."""
    cfg = cfg or load_config()
    N = cfg["numerics"]["fock_levels"]
    w01 = cfg["oscillator"]["w01"]
    dt = cfg["numerics"]["dt_s"]
    format_name = cfg["fixed_point"]["format"]
    int_bits, frac_bits = Q_FORMATS[format_name]
    data_width = int_bits + frac_bits
    addr_width = max(1, int(np.ceil(np.log2(N))))

    n = np.arange(N, dtype=float)
    theta = w01 * (n + 0.5) * dt
    rot_re = quantize(np.cos(theta), ROM_INT_BITS, ROM_FRAC_BITS)
    rot_im = quantize(np.sin(theta), ROM_INT_BITS, ROM_FRAC_BITS)

    write_hex_file(RTL_ROM_DIR / "rot_re_rom.hex", rot_re, ROM_FRAC_BITS, ROM_DATA_WIDTH)
    write_hex_file(RTL_ROM_DIR / "rot_im_rom.hex", rot_im, ROM_FRAC_BITS, ROM_DATA_WIDTH)

    params = {
        "N_LEVELS": N,
        "DATA_WIDTH": data_width,
        "FRAC_BITS": frac_bits,
        "ADDR_WIDTH": addr_width,
        "ROM_DATA_WIDTH": ROM_DATA_WIDTH,
        "ROM_FRAC_BITS": ROM_FRAC_BITS,
    }

    defines = "\n".join(f"`define {name} {value}" for name, value in params.items())
    params_vh = f"""// Generated by rtl/rom/gen_roms.py from config/default.yaml. Do not hand-edit.
// State format: {format_name} (CLAUDE.md section 7). ROM format: Q{ROM_INT_BITS}.{ROM_FRAC_BITS}
// (wider than the state on purpose -- see the ROM_DATA_WIDTH comment in this file).
`ifndef ROM_PARAMS_VH
`define ROM_PARAMS_VH
{defines}
`endif
"""
    (RTL_ROM_DIR / "rom_params.vh").write_text(params_vh)

    return params


if __name__ == "__main__":
    params = generate_free_evolution_roms()
    print("Generated ROMs: " + " ".join(f"{k}={v}" for k, v in params.items()))
